function toks(d){
  const out=new Set();
  // разбиваем строки, учитывая что "Название (a, b)" -> берем содержимое
  d.comp.join(";").replace(/—/g,",").split(/[,;:()\n]/).forEach(t=>{
    t=norm(t).replace(/\b(тесто|начинка|основа|покрыт(а|ы)?( розовым шоколадом и)?)\b/g," ").replace(/\s+/g," ").trim();
    t=t.replace(/^и /,"").replace(/^с /,"").trim();
    if(!t||t.length<3)return;
    for(const [re,c] of CANON){if(re.test(t)){t=c;break}}
    t=t.replace(/ \d+[,.]?\d*%$/,"").trim();
    for(const [re,c] of CANON){if(re.test(t)){t=c;break}}
    if(DROP.test(t))return;
    out.add(t);
  });
  return [...out];
}
